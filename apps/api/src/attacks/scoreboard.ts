import type { AttackResult, Category } from "./suite.js";

/** Render the attack scoreboard as Markdown (docs/ATTACKS.md). Numbers come only from the run. */
export function renderScoreboard(results: AttackResult[], meta: { ranAt: string; commit: string | null; durationMs: number }): string {
  const succeeded = results.filter((r) => r.succeeded);
  const cats = [...new Set(results.map((r) => r.category))] as Category[];
  const esc = (s: string) => s.replaceAll("|", "\\|").replaceAll("\n", " ");
  const lines: string[] = [];
  lines.push("# Attack scoreboard");
  lines.push("");
  lines.push(`**Attacks run: ${results.length} · Attacks succeeded: ${succeeded.length}**`);
  lines.push("");
  lines.push(
    `Generated by \`pnpm attacks\` on ${meta.ranAt}${meta.commit ? ` at commit \`${meta.commit}\`` : ""} in ${(meta.durationMs / 1000).toFixed(1)} s. ` +
      "Every attack runs against the real code paths (PostgreSQL, the HTTP API, the executor, the grounding verifier, webhook ingress) with the **MOCK** provider and scripted or **Mock AI** models. " +
      "No Airwallex sandbox or live Claude calls are involved. An attack counts as *succeeded* only if its unsafe outcome is observed afterwards. An error message on its own does not count as a block.",
  );
  lines.push("");
  lines.push("| Category | Run | Succeeded |");
  lines.push("| --- | ---: | ---: |");
  for (const c of cats) {
    const rs = results.filter((r) => r.category === c);
    lines.push(`| ${c} | ${rs.length} | ${rs.filter((r) => r.succeeded).length} |`);
  }
  lines.push("");
  for (const c of cats) {
    lines.push(`## ${c}`);
    lines.push("");
    lines.push("| ID | Attack | Threat | Result | What happened | Defence |");
    lines.push("| --- | --- | --- | --- | --- | --- |");
    for (const r of results.filter((x) => x.category === c)) {
      lines.push(`| ${r.id} | ${esc(r.title)} | ${esc(r.threat)} | ${r.succeeded ? "**SUCCEEDED**" : "Blocked"} | ${esc(r.observed)} | ${esc(r.defence)} |`);
    }
    lines.push("");
  }
  lines.push("## Limits of this scoreboard");
  lines.push("");
  lines.push("- It tests Sentinel's own controls. It cannot show how real banks or the real Airwallex sandbox behave; those runs are pending keys.");
  lines.push("- The AI attacks use scripted \"compromised\" models that do exactly what the injected text asks. That is a worst case for obedience, but it is not a measurement of a real model's behaviour.");
  lines.push("- The audit-tamper attack assumes a database superuser. The hash chain detects the edit, but it cannot prevent a superuser from rewriting the whole chain or deleting its newest entries. Exported checkpoints (T5) narrow that gap.");
  lines.push("");
  return lines.join("\n");
}
