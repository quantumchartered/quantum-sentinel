import { type Db, createUser } from "@sentinel/db";
import type { ModelClient } from "../agent/model.js";
import { AttackProvider } from "../attacks/suite.js";
import { EVAL_CASES, type CaseOutcome, type EvalCase } from "./cases.js";

export interface EvalResult {
  case: EvalCase;
  outcome: CaseOutcome | null;
  error: string | null;
  /** Decision, final state (if specified) and every case check all match. */
  pass: boolean;
  durationMs: number;
}

export async function runEval(
  db: Db,
  org: string,
  investigator: { model: ModelClient; modelId: string; label: string },
  only?: string[],
): Promise<EvalResult[]> {
  const provider = new AttackProvider(db, org);
  const approver = await createUser(db, org, { displayName: "Eval Approver", role: "APPROVER" });
  const env = {
    db,
    org,
    provider,
    keys: { current: { version: "eval", secret: "e".repeat(48) }, all: { eval: "e".repeat(48) } },
    investigator,
    approverId: `user:${approver.id}`,
  };
  const results: EvalResult[] = [];
  for (const c of EVAL_CASES.filter((x) => !only || only.includes(x.id))) {
    provider.balances.set("USD", 6_000_000n);
    provider.changedBeneficiaries.clear();
    const t0 = Date.now();
    try {
      const o = await c.run(env);
      const pass =
        o.decision === c.expected.decision && (c.expected.finalState === undefined || o.finalState === c.expected.finalState) && o.checks.every((k) => k.ok);
      results.push({ case: c, outcome: o, error: null, pass, durationMs: Date.now() - t0 });
    } catch (err) {
      results.push({ case: c, outcome: null, error: err instanceof Error ? err.message : String(err), pass: false, durationMs: Date.now() - t0 });
    }
  }
  return results;
}

function median(xs: number[]): number | null {
  if (!xs.length) return null;
  const s = [...xs].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m]! : Math.round((s[m - 1]! + s[m]!) / 2);
}

export function summarize(results: EvalResult[]) {
  const outs = results.map((r) => r.outcome).filter((o): o is CaseOutcome => !!o);
  const ai = outs.map((o) => o.ai).filter((a): a is NonNullable<CaseOutcome["ai"]> => !!a);
  return {
    cases: results.length,
    passed: results.filter((r) => r.pass).length,
    decisionsCorrect: results.filter((r) => r.outcome && r.outcome.decision === r.case.expected.decision).length,
    aiRuns: ai.length,
    aiVerifiedAndAgreeing: outs.filter((o) => o.ai?.verified && o.ai.recommendation === o.decision).length,
    aiToolCalls: ai.reduce((n, a) => n + a.toolCalls, 0),
    aiCostMicroUsd: ai.reduce((n, a) => n + BigInt(a.costMicroUsd), 0n),
    unsafeAttempts: outs.reduce((n, o) => n + o.unsafeAttempts, 0),
    unsafeBlocked: outs.reduce((n, o) => n + o.unsafeBlocked, 0),
    duplicatesPrevented: outs.reduce((n, o) => n + o.duplicatesPrevented, 0),
    escalations: outs.filter((o) => o.decision === "ESCALATE" || o.finalState === "ESCALATED").length,
    medianTimeToRecommendationMs: median(outs.map((o) => o.timeToRecommendationMs).filter((x): x is number => x !== null)),
    medianAiMs: median(ai.map((a) => a.durationMs)),
  };
}

export function renderEval(results: EvalResult[], meta: { ranAt: string; commit: string | null; investigator: string; model: string }): string {
  const s = summarize(results);
  const usd = (micro: bigint) => `$${(Number(micro) / 1_000_000).toFixed(4)}`;
  const L: string[] = [];
  L.push("# Evaluation");
  L.push("");
  L.push(`**${s.passed} / ${s.cases} cases pass** · decisions correct ${s.decisionsCorrect}/${s.cases} · unsafe actions blocked ${s.unsafeBlocked}/${s.unsafeAttempts} · duplicate transfers prevented ${s.duplicatesPrevented}`);
  L.push("");
  L.push(
    `Generated by \`pnpm eval\` on ${meta.ranAt}${meta.commit ? ` at commit \`${meta.commit}\`` : ""}. ` +
      `Provider: **MOCK** (Sentinel's simulated Airwallex; no sandbox calls). Investigator: **${meta.investigator}** (\`${meta.model}\`). ` +
      "Each case builds the incident through the product's own functions, against a real local PostgreSQL. The deterministic policy decides and the investigator explains. Times are measured on this machine, from database timestamps. " +
      "There is no baseline: this table reports what happened, not an improvement over anything.",
  );
  L.push("");
  L.push("| Measure | Result |");
  L.push("| --- | --- |");
  L.push(`| Cases passing (decision, final state, case checks) | ${s.passed} / ${s.cases} |`);
  L.push(`| Deterministic decision as expected | ${s.decisionsCorrect} / ${s.cases} |`);
  L.push(`| AI reports verified and agreeing with policy | ${s.aiVerifiedAndAgreeing} / ${s.aiRuns} runs |`);
  L.push(`| Unsafe actions attempted / blocked | ${s.unsafeAttempts} / ${s.unsafeBlocked} |`);
  L.push(`| Duplicate transfers prevented | ${s.duplicatesPrevented} |`);
  L.push(`| Escalated to a person | ${s.escalations} cases |`);
  L.push(`| Median time to first recommendation | ${s.medianTimeToRecommendationMs ?? "n/a"} ms |`);
  L.push(`| Median investigator run | ${s.medianAiMs ?? "n/a"} ms |`);
  L.push(`| Investigator tool calls / cost | ${s.aiToolCalls} / ${usd(s.aiCostMicroUsd)} |`);
  L.push("");
  L.push("| ID | Case | Expected | Actual | Pass | Time to rec. | Investigator | Unsafe blocked | Notes |");
  L.push("| --- | --- | --- | --- | --- | ---: | --- | --- | --- |");
  for (const r of results) {
    const o = r.outcome;
    const exp = `${r.case.expected.decision}${r.case.expected.finalState ? ` → ${r.case.expected.finalState}` : ""}`;
    const act = o ? `${o.decision}${r.case.expected.finalState ? ` → ${o.finalState}` : ""}` : "error";
    const ai = o?.ai ? `${o.ai.status.toLowerCase()}${o.ai.recommendation ? ` (${o.ai.recommendation})` : ""}, ${o.ai.toolCalls} tools` : "-";
    const notes = [r.case.expected.note, o?.notes, ...(o?.checks.filter((k) => !k.ok).map((k) => `FAILED CHECK: ${k.name}`) ?? []), r.error ? `ERROR: ${r.error}` : ""].filter(Boolean).join("; ");
    L.push(
      `| ${r.case.id} | ${r.case.title} (${r.case.category}) | ${exp} | ${act} | ${r.pass ? "✓" : "✗"} | ${o?.timeToRecommendationMs ?? "-"} ms | ${ai} | ${o && o.unsafeAttempts ? `${o.unsafeBlocked}/${o.unsafeAttempts}` : "-"} | ${notes.replaceAll("|", "\\|")} |`,
    );
  }
  L.push("");
  L.push("## Reading this honestly");
  L.push("");
  L.push("- **MOCK provider.** Provider behaviour follows the documented Airwallex lifecycle as Sentinel simulates it. Real sandbox timings and payload shapes are not yet measured (keys pending).");
  L.push(
    meta.investigator.startsWith("Mock")
      ? "- **Mock AI.** The investigator here is a deterministic stand-in. It shows that the tool, verifier and proposal paths work end to end, not how well a real model reasons. Run `pnpm eval --live` with an Anthropic key to measure Claude (cost is shown above)."
      : "- **Live model.** The investigator calls Claude; costs above are real API charges for this run.",
  );
  L.push("- **Times** are local, in-process measurements on a developer machine. They are not service-level figures.");
  L.push("");
  return L.join("\n");
}
